#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn stage_texts_fit_the_font() {
        // Todo texto do palco precisa ter glifo na fonte (sem cair no '?').
        for lang in [Lang::Pt, Lang::En] {
            for key in [
                Key::Fight,
                Key::Victory,
                Key::Defeat,
                Key::LeagueDone,
                Key::Critical,
                Key::Miss,
                Key::Next,
                Key::Training,
                Key::Auto,
                Key::Continue,
                Key::Round,
                Key::ChooseAction,
                Key::Paused,
                Key::PointsShort,
                Key::PointsInMenu,
                Key::ClickFight,
                Key::DamageWord,
                Key::Missed,
                Key::Fell,
                Key::TimeUp,
                Key::NoStamina,
                Key::OutOfRange,
                Key::Unavailable,
                Key::ActAdvance,
                Key::ActRetreat,
                Key::ActLight,
                Key::ActMedium,
                Key::ActHeavy,
                Key::ActDefend,
                Key::ActRecover,
                Key::ActTaunt,
                Key::NarAdvance,
                Key::NarRetreat,
                Key::NarDefend,
                Key::NarRecover,
                Key::NarTaunt,
                Key::InfoDefend,
                Key::InfoRecover,
                Key::InfoTaunt,
            ] {
                for c in t(lang, key).chars() {
                    if c != '?' {
                        assert_ne!(assets::glyph(c), assets::glyph('?'), "{c:?} em {key:?}");
                    }
                }
            }
        }
    }
}
