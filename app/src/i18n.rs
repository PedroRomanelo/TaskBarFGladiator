use serde::{Deserialize, Serialize};

/// Idioma.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Lang {
    /// Português do Brasil.
    Pt,
    /// Inglês.
    En,
}

impl Lang {
    /// O outro idioma.
    pub fn toggle(self) -> Lang {
        match self {
            Lang::Pt => Lang::En,
            Lang::En => Lang::Pt,
        }
    }
}

